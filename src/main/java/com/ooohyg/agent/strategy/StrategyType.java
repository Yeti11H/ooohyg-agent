package com.ooohyg.agent.strategy;

/**
 * 执行策略类型。
 *
 * <p>本枚举是"标签"，不是"行为分派器"。它只用于日志、事件、监控和
 * 序列化时的策略标识，<b>不用于根据类型做不同的事</b>。
 *
 * <p>判据：如果哪天你在代码里写出
 * {@code if (strategy.type() == REACT) { ... }} 这样的逻辑，
 * 说明抽象泄漏了——应该让策略自己处理差异，而不是让调用方按类型分支。
 *
 * <p>本枚举是"开放枚举"：每新增一种执行策略，在此增加一个值。
 * 接受这个代价，换取日志和监控里"能知道这次跑的是哪种策略"。
 */
public enum StrategyType {

    /**
     * ReAct 策略。
     *
     * <p>思考-行动-观察循环，边想边做。
     */
    REACT,

    /**
     * Plan-and-Execute 策略。
     *
     * <p>先一次性生成计划，再逐步执行，失败时可重新规划。
     */
    PLAN_AND_EXECUTE,

    /**
     * Reflexion 策略。
     *
     * <p>包裹型策略：评估被包裹策略的结果，不合格时修正并重新执行。
     */
    REFLEXION
}